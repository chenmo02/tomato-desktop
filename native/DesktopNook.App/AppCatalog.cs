    private static bool IsShortcutFile(string path)=>new[]{".lnk",".url"}.Contains(Path.GetExtension(path),StringComparer.OrdinalIgnoreCase);
    private static bool IsNoise(string name)=>NoiseWords.Any(word=>name.Contains(word,StringComparison.OrdinalIgnoreCase));
    private static bool IsSystemAppId(string path)=>SystemAppIds.Any(prefix=>path.StartsWith(prefix,StringComparison.OrdinalIgnoreCase));
    private static bool IsSystemFolder(string path)
    {
        var dir=Path.GetDirectoryName(path);if(string.IsNullOrEmpty(dir))return false;
        return dir.Split(Path.DirectorySeparatorChar,Path.AltDirectorySeparatorChar).Any(SystemFolders.Contains);
    }

    public static List<CatalogEntry> Load(NookStore store)
    {
        var candidates=new List<CatalogEntry>();
        var sources=new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        // 开始菜单与桌面只各遍历一次；内置「文件管理」也从同一份结果里找。
        var links=new List<(string Path,string Group)>();
        foreach(var root in new[]{Environment.GetFolderPath(Environment.SpecialFolder.StartMenu),Environment.GetFolderPath(Environment.SpecialFolder.CommonStartMenu)})
        {
            var programs=Path.Combine(root,"Programs");if(!Directory.Exists(programs))continue;
            foreach(var path in SafeEnumerate(programs))links.Add((path,"开始菜单"));
        }
        foreach(var desktop in store.DesktopRoots.Where(Directory.Exists))
        {
            try{foreach(var path in Directory.EnumerateFiles(desktop))links.Add((path,"桌面"));}
            catch{/* 无权访问某个桌面目录时跳过 */}
        }
        void AddLink(string path,string group)
        {
            if(!IsShortcutFile(path)||!sources.Add(path))return;
            try{if((File.GetAttributes(path)&FileAttributes.Hidden)!=0)return;}catch{return;}
            var name=Path.GetFileNameWithoutExtension(path);
            if(name.Length==0||IsNoise(name))return;
            bool hidden=SystemNames.Contains(name)||IsSystemFolder(path);
            candidates.Add(new CatalogEntry(name,path,group,path,false,hidden));
        }
        var explorer=links.Select(l=>l.Path).FirstOrDefault(p=>
        {
            var name=Path.GetFileNameWithoutExtension(p);
            return string.Equals(name,"File Explorer",StringComparison.OrdinalIgnoreCase)||name is "文件资源管理器" or "资源管理器" or "Windows 资源管理器";
        });
        if(explorer is not null){sources.Add(explorer);candidates.Add(new CatalogEntry("文件管理",explorer,"常用",explorer,false,false));}
        else candidates.Add(new CatalogEntry("文件管理","shell:MyComputerFolder","常用","shell:MyComputerFolder",true,false));
        foreach(var (path,group) in links)AddLink(path,group);
        // 开始菜单里已经有的正常应用，不必再去读 AppsFolder 指针的 Path 属性。
        var visibleNames=new HashSet<string>(candidates.Where(e=>!e.Hidden).Select(e=>e.Name),StringComparer.OrdinalIgnoreCase);
        try{candidates.AddRange(AppsFolderEntries(visibleNames));}catch{/* 系统应用枚举不可用时，普通快捷方式照样可用 */}
        // 同名条目只留一个；若一条是隐藏的系统项、另一条是正常应用，优先保留正常应用。
        var byName=new Dictionary<string,CatalogEntry>(StringComparer.OrdinalIgnoreCase);
        foreach(var entry in candidates)
            if(!byName.TryGetValue(entry.Name,out var previous)||(previous.Hidden&&!entry.Hidden))byName[entry.Name]=entry;
        return byName.Values.OrderBy(e=>GroupOrder(e.Group)).ThenBy(e=>e.Name,StringComparer.CurrentCulture).ToList();
    }
    private static int GroupOrder(string group)=>group switch{"常用"=>0,"开始菜单"=>1,"系统应用"=>2,"桌面"=>3,_=>4};
    private static IEnumerable<string> SafeEnumerate(string root)
    {
        var queue=new Queue<(string Path,int Depth)>();queue.Enqueue((root,0));
        while(queue.Count>0)
        {
            var (dir,depth)=queue.Dequeue();if(depth>3)continue;
            string[] files=[],folders=[];
            try{files=Directory.GetFiles(dir);folders=Directory.GetDirectories(dir);}catch{continue;}
            foreach(var file in files)yield return file;
            foreach(var folder in folders)
            {
                try{if((File.GetAttributes(folder)&FileAttributes.Hidden)!=0)continue;}catch{continue;}
                queue.Enqueue((folder,depth+1));
            }
        }
    }
    // Windows 11 的「设置」「照片」「计算器」等没有 .lnk，只能从 shell:AppsFolder 虚拟文件夹枚举。
    private static List<CatalogEntry> AppsFolderEntries(HashSet<string> visibleNames)
    {
        var list=new List<CatalogEntry>();
        object? shell=null,folder=null,items=null;
        try
        {
            var type=Type.GetTypeFromProgID("Shell.Application");if(type is null)return list;
            shell=Activator.CreateInstance(type);
            folder=((dynamic)shell!).NameSpace("shell:AppsFolder");
            if(folder is null)return list;
            items=((dynamic)folder).Items();
            int count;
            try{count=(int)((dynamic)items).Count;}catch{return list;}
            for(int i=0;i<count;i++)
            {
                object? item=null;
                try
                {
                    item=((dynamic)items).Item(i);
                    string name=Convert.ToString(((dynamic)item!).Name)??"";
                    // 先读名称再决定是否需要 Path，省掉噪声、重复项上的 COM 属性调用。
                    if(name.Length==0||IsNoise(name)||visibleNames.Contains(name))continue;
                    string path=Convert.ToString(((dynamic)item!).Path)??"";
                    if(path.Length==0)continue;
                    if(!path.StartsWith("shell:AppsFolder\\",StringComparison.OrdinalIgnoreCase))
                    {
                        if(path.Contains('!')&&!path.Contains(':')&&!path.Contains('\\'))path="shell:AppsFolder\\"+path;
                        else continue;
                    }
                    bool hidden=SystemNames.Contains(name)||IsSystemAppId(path);
                    list.Add(new CatalogEntry(name,path,"系统应用",path,true,hidden));
                }
                catch{continue;}
                finally{if(item is not null&&Marshal.IsComObject(item))Marshal.FinalReleaseComObject(item);}
            }
        }
        catch{return list;}
        finally
        {
            foreach(var com in new[]{items,folder,shell})
                if(com is not null&&Marshal.IsComObject(com))Marshal.FinalReleaseComObject(com);
        }
        return list;
    }

