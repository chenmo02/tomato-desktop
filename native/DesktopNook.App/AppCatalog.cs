    // 生成可被双击启动、且图标能被系统正确解析的快捷方式，保存到番茄桌面数据目录的缓存里。
    public static void Materialize(CatalogEntry entry,string target)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(target)!);
        if(!entry.AppRef){File.Copy(entry.Source,target,true);return;}
        if(File.Exists(target))File.Delete(target);
        Marshal.ThrowExceptionForHR(SHParseDisplayName(entry.Source,IntPtr.Zero,out var pidl,0,out _));
        try
        {
            var link=(IShellLinkW)new ShellLink();
            try{link.SetIDList(pidl);((IPersistFile)link).Save(target,true);}
            finally{Marshal.ReleaseComObject(link);}
        }
        finally{CoTaskMemFree(pidl);}
        if(!File.Exists(target))throw new IOException("无法为系统应用创建快捷方式："+entry.Name);
    }
