// 控制台校验入口：在真实机器上量一次枚举耗时与过滤结果，不触碰用户数据目录。
internal static class CatalogVerification
{
    public static int Run(string sandbox)
    {
        var root=Path.Combine(Path.GetFullPath(sandbox),"catalog-check");
        var desktops=new[]{Environment.GetFolderPath(Environment.SpecialFolder.DesktopDirectory),Environment.GetFolderPath(Environment.SpecialFolder.CommonDesktopDirectory)};
        var store=new NookStore(Path.Combine(root,"Data"),desktops,new WindowsRecycleBin());
        var watch=Stopwatch.StartNew();
        var entries=AppCatalog.Load(store);
        watch.Stop();
        var shown=entries.Where(e=>!e.Hidden).ToList();
        var lines=new List<string>{$"catalog-total={entries.Count} shown={shown.Count} hidden={entries.Count-shown.Count} elapsed-ms={watch.ElapsedMilliseconds}"};
        foreach(var group in shown.GroupBy(e=>e.Group))lines.Add($"  group {group.Key}: {group.Count()}");
        lines.Add("  sample: "+string.Join(" / ",shown.Take(12).Select(e=>e.Name)));
        lines.Add("  hidden sample: "+string.Join(" / ",entries.Where(e=>e.Hidden).Take(12).Select(e=>e.Name)));
        lines.Add("  shown all: "+string.Join(" / ",shown.Select(e=>e.Name)));
        File.WriteAllLines(Path.Combine(root,"catalog-check.txt"),lines);
        foreach(var line in lines)Console.WriteLine(line);
        return shown.Count>0?0:1;
    }

    // 在沙箱窗口里实测「打开页面 → 列表就绪 → 首屏图标请求数」。
    public static async Task RunUi(MainWindow window,string reportPath)
    {
        var lines=new List<string>{"step=start"};
        bool ok=false;
        try
        {
            var show=typeof(MainWindow).GetMethod("ShowCatalogView",BindingFlags.Instance|BindingFlags.NonPublic)!;
            var cardsField=typeof(MainWindow).GetField("_catalogCards",BindingFlags.Instance|BindingFlags.NonPublic)!;
            var watch=Stopwatch.StartNew();
            show.Invoke(window,null);
            long openMs=watch.ElapsedMilliseconds;
            lines.Add("step=show-invoked open-sync-ms="+openMs);
            var cards=(System.Collections.IList)cardsField.GetValue(window)!;
            for(int i=0;i<120&&cards.Count==0;i++)await Task.Delay(50);
            long readyMs=watch.ElapsedMilliseconds;
            lines.Add($"step=cards cards-ready-ms={readyMs} count={cards.Count}");
            // 让 Dispatcher 处理完一轮滚动/布局，再统计实际入队的图标请求。
            await Task.Delay(400);
            int requested=0;
            foreach(var card in cards)
            {
                var icon=(ShellIcon)card.GetType().GetProperty("Icon",BindingFlags.Instance|BindingFlags.Public)!.GetValue(card)!;
                if(icon.IconRequested)requested++;
            }
            lines.Add($"open-sync-ms={openMs} cards-ready-ms={readyMs}");
            lines.Add($"surface-visible={window.CatalogSurface.Visibility==Visibility.Visible} cards={cards.Count} icon-requested={requested} groups={window.CatalogGroups.Children.Count}");
            // 开关已迁入设置页：直接改 AppSettings 偏好，再走与设置页相同的重建路径。
            var refresh=typeof(MainWindow).GetMethod("ApplySystemItemsPreference",BindingFlags.Instance|BindingFlags.NonPublic)!;
            window.Settings=window.Settings with {ShowSystemItems=true};refresh.Invoke(window,null);
            lines.Add($"toggle-show-system cards={cards.Count}");
            window.Settings=window.Settings with {ShowSystemItems=false};refresh.Invoke(window,null);
            var filter=typeof(MainWindow).GetMethod("ApplyCatalogFilter",BindingFlags.Instance|BindingFlags.NonPublic)!;
            window.CatalogSearch.Text="微信";filter.Invoke(window,null);
            int visible=0;
            foreach(var card in cards)
                if(((Border)card.GetType().GetProperty("Card",BindingFlags.Instance|BindingFlags.Public)!.GetValue(card)!).Visibility==Visibility.Visible)visible++;
            lines.Add($"toggle-default cards={cards.Count} search-visible={visible}");
            window.CatalogSearch.Text="";filter.Invoke(window,null);
            ok=cards.Count>0&&openMs<500&&requested<cards.Count&&visible>0;
        }
        catch(Exception ex){lines.Add("error="+ex);}
        File.WriteAllLines(reportPath,lines);
        foreach(var line in lines)Console.WriteLine(line);
        Application.Current.Shutdown(ok?0:1);
    }
